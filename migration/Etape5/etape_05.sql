CREATE TABLE serveur (
    id_serveur INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_serveur VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE table_salle (
    id_table INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_table INTEGER NOT NULL UNIQUE
        CHECK (numero_table BETWEEN 1 AND 8)
);

